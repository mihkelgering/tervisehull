-- Forward migration: room for the MD interaction workbook
-- (medical-doctor-input, CICILY_MD_INTERACTION_V2 tabs).
--
-- Runs after 001-002 on a fresh volume; apply with psql to an existing one.
-- Everything here is additive or widens a CHECK; no seeded row becomes
-- invalid. Why each change exists is in wiki/database.md ("Workbook import
-- support") and the gap analysis that preceded it.
--
-- Covers:
--   1. interaction_topics            one row per workbook tab (topic summary,
--                                    factor descriptions, default risk)
--   2. interaction_rules             MD clinical fields, effect direction,
--                                    workbook trace, medical reviewer
--   3. evidence_findings             one finding per rule x source x row,
--                                    with study design and effect numbers
--   4. timing_recommendations        structured timing (anchor, window,
--                                    posture, water, time of day, strength)
--   5. single-concept timing rules   gate accepts rule_scope='timing_context'
--                                    with one participant
--   6. participant alternatives      "any one of these" via alternative_group
--   7. vocabularies                  interaction_type, condition_kind,
--                                    concept_type/dosage form, timing_type
--   8. risk_levels.can_publish       the 'review' level never publishes
--   9. case-insensitive DOI uniqueness

BEGIN;

-- ---------------------------------------------------------------------------
-- 1. Topics: the summary block at the top of every workbook tab.
-- ---------------------------------------------------------------------------
CREATE TABLE interaction_topics (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  uid uuid NOT NULL DEFAULT gen_random_uuid() UNIQUE,
  public_id text NOT NULL UNIQUE,
  title_text_id bigint NOT NULL REFERENCES translation_keys(id) ON DELETE RESTRICT,
  -- "What happens?", "Proposed guidance", "When does it apply?",
  -- "Questions / uncertainty", "Related entries / notes".
  what_happens_text_id bigint REFERENCES translation_keys(id) ON DELETE RESTRICT,
  proposed_guidance_text_id bigint REFERENCES translation_keys(id) ON DELETE RESTRICT,
  when_applies_text_id bigint REFERENCES translation_keys(id) ON DELETE RESTRICT,
  open_questions_text_id bigint REFERENCES translation_keys(id) ON DELETE RESTRICT,
  notes_text_id bigint REFERENCES translation_keys(id) ON DELETE RESTRICT,
  -- "Factor 1 or group", "Factor 2 or group", "Other factors / group members":
  -- the MD's description of the topic's sides, kept as written.
  factor_1_text_id bigint REFERENCES translation_keys(id) ON DELETE RESTRICT,
  factor_2_text_id bigint REFERENCES translation_keys(id) ON DELETE RESTRICT,
  other_factors_text_id bigint REFERENCES translation_keys(id) ON DELETE RESTRICT,
  -- "Risk (optional)": the default every case inherits unless it overrides.
  default_risk_level_id bigint REFERENCES risk_levels(id) ON DELETE RESTRICT,
  -- "How are factors related?"
  factor_relation text NOT NULL DEFAULT 'to_clarify' CHECK (
    factor_relation IN ('single_pair', 'any_member_of_group', 'all_factors_together', 'related_cases', 'to_clarify')
  ),
  -- "Handoff status" plus the state after the team has taken it over.
  handoff_status text NOT NULL DEFAULT 'working_draft' CHECK (
    handoff_status IN ('working_draft', 'ready_for_team_review', 'reviewed')
  ),
  -- "Your name" on the tab; free text, not a users row (MDs are not app users).
  author_name text,
  source_workbook_sheet text,
  created_at timestamptz NOT NULL DEFAULT now(),
  created_by bigint,
  updated_at timestamptz NOT NULL DEFAULT now(),
  updated_by bigint,
  CONSTRAINT interaction_topics_public_id_not_empty CHECK (length(trim(public_id)) > 0)
);

CREATE UNIQUE INDEX uq_interaction_topics_workbook_sheet
  ON interaction_topics(source_workbook_sheet) WHERE source_workbook_sheet IS NOT NULL;
CREATE INDEX idx_interaction_topics_default_risk ON interaction_topics(default_risk_level_id);

-- ---------------------------------------------------------------------------
-- 2. Rules: the per-case columns of the workbook Cases table.
-- ---------------------------------------------------------------------------
ALTER TABLE interaction_rules
  ADD COLUMN topic_id bigint REFERENCES interaction_topics(id) ON DELETE RESTRICT,
  -- base_risk_level_id stays NOT NULL; this records that it came from the
  -- topic default rather than a case-level "Risk override".
  ADD COLUMN is_risk_inherited_from_topic boolean NOT NULL DEFAULT false,
  -- "Other factors and group scope"
  ADD COLUMN scope_note_text_id bigint REFERENCES translation_keys(id) ON DELETE RESTRICT,
  -- "Conditions and exceptions" as the MD wrote them (free text; structured
  -- thresholds still go to rule_conditions).
  ADD COLUMN conditions_text_id bigint REFERENCES translation_keys(id) ON DELETE RESTRICT,
  -- "Clinical conclusion / guidance", and its labelled parts where the MD
  -- split them: Olulisus (significance) and Arvuline mõju (numeric effect).
  ADD COLUMN clinical_conclusion_text_id bigint REFERENCES translation_keys(id) ON DELETE RESTRICT,
  ADD COLUMN significance_text_id bigint REFERENCES translation_keys(id) ON DELETE RESTRICT,
  ADD COLUMN numeric_effect_text_id bigint REFERENCES translation_keys(id) ON DELETE RESTRICT,
  -- Direction of the interaction. Negative findings are first-class
  -- ('no_meaningful_effect'), which the copy must be able to say.
  ADD COLUMN effect_direction text CHECK (
    effect_direction IS NULL OR effect_direction IN (
      'increased_exposure', 'decreased_exposure',
      'increased_absorption', 'decreased_absorption',
      'increased_effect', 'decreased_effect',
      'additive_toxicity', 'no_meaningful_effect', 'mixed', 'unknown'
    )
  ),
  -- Workbook trace: tab name + "Case name" identify a case across re-imports.
  ADD COLUMN source_workbook_sheet text,
  ADD COLUMN source_workbook_case_name text,
  -- Who gave medical approval (concepts and sources already record this).
  ADD COLUMN medical_reviewed_by_user_id bigint REFERENCES users(id) ON DELETE SET NULL,
  ADD COLUMN medical_reviewed_at timestamptz;

CREATE INDEX idx_interaction_rules_topic ON interaction_rules(topic_id);
CREATE INDEX idx_interaction_rules_medical_reviewer ON interaction_rules(medical_reviewed_by_user_id);
CREATE UNIQUE INDEX uq_interaction_rules_workbook_case
  ON interaction_rules(source_workbook_sheet, source_workbook_case_name)
  WHERE source_workbook_sheet IS NOT NULL AND source_workbook_case_name IS NOT NULL;

-- Pairs beyond drug_x, plus administration instructions for one drug.
ALTER TABLE interaction_rules DROP CONSTRAINT interaction_rules_interaction_type_check;
ALTER TABLE interaction_rules ADD CONSTRAINT interaction_rules_interaction_type_check CHECK (
  interaction_type IN (
    'drug_food', 'drug_supplement', 'drug_drug', 'drug_condition', 'drug_measurement',
    'supplement_condition', 'supplement_measurement', 'general_factor',
    'supplement_food', 'supplement_supplement', 'food_food', 'drug_lifestyle',
    'drug_administration'
  )
);

-- ---------------------------------------------------------------------------
-- 3. Evidence findings: one row per workbook Evidence row. A source can give
--    several distinct findings for the same case (the seed's
--    interaction_rule_sources.note holds one).
-- ---------------------------------------------------------------------------
CREATE TABLE evidence_findings (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  uid uuid NOT NULL DEFAULT gen_random_uuid() UNIQUE,
  interaction_rule_id bigint NOT NULL,
  evidence_source_id bigint NOT NULL,
  finding_order int NOT NULL DEFAULT 1,
  -- "Finding / excerpt", "Conditions / limitations", "Page / section",
  -- "Notes / guidance from source". Source language, not display copy.
  finding_text text NOT NULL,
  limitations_text text,
  source_locator text,
  source_guidance_text text,
  study_design text CHECK (
    study_design IS NULL OR study_design IN (
      'rct', 'crossover', 'cohort', 'case_control', 'case_series', 'case_report',
      'pk_study', 'in_vitro', 'animal', 'review', 'meta_analysis', 'label', 'guideline', 'other'
    )
  ),
  population text CHECK (
    population IS NULL OR population IN ('healthy_volunteers', 'patients', 'animals', 'in_vitro', 'mixed', 'unknown')
  ),
  sample_size int CHECK (sample_size IS NULL OR sample_size > 0),
  -- One number per row; a second metric is a second row.
  effect_metric text CHECK (
    effect_metric IS NULL OR effect_metric IN (
      'auc_ratio', 'cmax_ratio', 'auc_percent_change', 'cmax_percent_change',
      'bioavailability_ratio', 'odds_ratio', 'hazard_ratio', 'relative_risk',
      'absolute_change', 'percent_change', 'other'
    )
  ),
  effect_value numeric,
  effect_ci_low numeric,
  effect_ci_high numeric,
  p_value numeric CHECK (p_value IS NULL OR (p_value >= 0 AND p_value <= 1)),
  -- What the number refers to ("simvastatin acid", "day 1", "patients arm").
  effect_note text,
  is_negative_finding boolean NOT NULL DEFAULT false,
  status text NOT NULL DEFAULT 'draft' CHECK (status IN ('draft', 'approved', 'retired')),
  created_at timestamptz NOT NULL DEFAULT now(),
  created_by bigint,
  updated_at timestamptz NOT NULL DEFAULT now(),
  updated_by bigint,
  CONSTRAINT evidence_findings_text_not_empty CHECK (length(trim(finding_text)) > 0),
  CONSTRAINT evidence_findings_finding_order_positive CHECK (finding_order > 0),
  CONSTRAINT uq_evidence_findings_rule_source_order UNIQUE (interaction_rule_id, evidence_source_id, finding_order),
  -- A finding belongs to a source that is linked to the rule.
  CONSTRAINT fk_evidence_findings_rule_source
    FOREIGN KEY (interaction_rule_id, evidence_source_id)
    REFERENCES interaction_rule_sources(interaction_rule_id, evidence_source_id) ON DELETE CASCADE,
  -- A value needs a metric; a CI needs a value and ordered bounds.
  CONSTRAINT evidence_findings_value_needs_metric CHECK (
    effect_value IS NULL OR effect_metric IS NOT NULL
  ),
  CONSTRAINT evidence_findings_ci_bounds CHECK (
    (effect_ci_low IS NULL AND effect_ci_high IS NULL)
    OR (effect_value IS NOT NULL AND effect_ci_low IS NOT NULL AND effect_ci_high IS NOT NULL
        AND effect_ci_low <= effect_ci_high)
  )
);

CREATE INDEX idx_evidence_findings_rule ON evidence_findings(interaction_rule_id);
CREATE INDEX idx_evidence_findings_source ON evidence_findings(evidence_source_id);

-- ---------------------------------------------------------------------------
-- 4. Timing: structured instructions. hours_mentioned/minutes_mentioned stay
--    for the seeded rows; new rows use the typed columns.
-- ---------------------------------------------------------------------------
ALTER TABLE timing_recommendations
  -- What the window is measured from.
  ADD COLUMN anchor text CHECK (
    anchor IS NULL OR anchor IN (
      'meal', 'breakfast', 'first_food_or_drink', 'waking', 'bedtime',
      'other_medicines', 'the_other_factor', 'last_dose'
    )
  ),
  ADD COLUMN relation text CHECK (
    relation IS NULL OR relation IN ('before', 'after', 'before_or_after', 'with', 'any_time')
  ),
  ADD COLUMN min_minutes int CHECK (min_minutes IS NULL OR min_minutes >= 0),
  ADD COLUMN max_minutes int CHECK (max_minutes IS NULL OR max_minutes >= 0),
  -- Rows of one rule sharing a non-null alternative_group are alternatives
  -- ("1 h before OR 2 h after"); rows with NULL are all required.
  ADD COLUMN alternative_group smallint CHECK (alternative_group IS NULL OR alternative_group > 0),
  ADD COLUMN time_of_day text CHECK (
    time_of_day IS NULL OR time_of_day IN ('morning', 'midday', 'evening', 'bedtime', 'consistent_time', 'any')
  ),
  ADD COLUMN stay_upright_minutes int CHECK (stay_upright_minutes IS NULL OR stay_upright_minutes > 0),
  ADD COLUMN with_water_ml_min int CHECK (with_water_ml_min IS NULL OR with_water_ml_min > 0),
  ADD COLUMN with_water_ml_max int CHECK (with_water_ml_max IS NULL OR with_water_ml_max > 0),
  -- "Nõude tugevus" / "Ajastuse tugevus".
  ADD COLUMN requirement_strength text CHECK (
    requirement_strength IS NULL OR requirement_strength IN (
      'strict_label_requirement', 'label_recommendation', 'practical_preference',
      'consistency_only', 'indication_linked', 'not_required'
    )
  ),
  ADD CONSTRAINT timing_recommendations_window_order CHECK (
    min_minutes IS NULL OR max_minutes IS NULL OR min_minutes <= max_minutes
  ),
  ADD CONSTRAINT timing_recommendations_water_order CHECK (
    with_water_ml_min IS NULL OR with_water_ml_max IS NULL OR with_water_ml_min <= with_water_ml_max
  ),
  -- A window needs something to measure from.
  ADD CONSTRAINT timing_recommendations_window_needs_anchor CHECK (
    (min_minutes IS NULL AND max_minutes IS NULL) OR (anchor IS NOT NULL AND relation IS NOT NULL)
  );

ALTER TABLE timing_recommendations DROP CONSTRAINT timing_recommendations_timing_type_check;
ALTER TABLE timing_recommendations ADD CONSTRAINT timing_recommendations_timing_type_check CHECK (
  timing_type IN (
    'avoid_together', 'separate_or_wait_time', 'keep_intake_stable', 'limit_amount',
    'monitor', 'ask_clinician', 'general_caution',
    'take_on_empty_stomach', 'take_with_food', 'take_at_time_of_day', 'avoid_after_stopping'
  )
);

