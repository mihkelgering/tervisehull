-- ---------------------------------------------------------------------------
-- 5 + 6 + 8. Publication gate and matcher.
-- ---------------------------------------------------------------------------
-- Changes from 001:
--   * a rule needs two required slots and two distinct required concepts,
--     except rule_scope = 'timing_context' (an instruction for one drug),
--     which needs one;
--   * the base risk level must be publishable;
--   * every non-retired evidence finding is approved.
CREATE OR REPLACE VIEW public_interaction_rule_eligibility AS
SELECT ir.id AS interaction_rule_id
FROM interaction_rules ir
JOIN risk_levels base_risk ON base_risk.id = ir.base_risk_level_id
WHERE ir.publication_status = 'published'
  AND ir.medical_review_status = 'approved'
  AND base_risk.can_publish
  AND (
    SELECT COUNT(DISTINCT irp.concept_id)
    FROM interaction_rule_participants irp
    WHERE irp.interaction_rule_id = ir.id
      AND irp.required_for_match = true
  ) >= CASE WHEN ir.rule_scope = 'timing_context' THEN 1 ELSE 2 END
  AND (
    SELECT COUNT(DISTINCT COALESCE(irp.alternative_group::bigint, -irp.id))
    FROM interaction_rule_participants irp
    WHERE irp.interaction_rule_id = ir.id
      AND irp.required_for_match = true
  ) >= CASE WHEN ir.rule_scope = 'timing_context' THEN 1 ELSE 2 END
  AND NOT EXISTS (
    SELECT 1
    FROM interaction_rule_participants irp
    JOIN health_concepts hc ON hc.id = irp.concept_id
    WHERE irp.interaction_rule_id = ir.id
      AND (hc.status <> 'published' OR NOT hc.can_trigger_matching)
  )
  AND NOT EXISTS (
    SELECT 1
    FROM locales l
    WHERE l.is_mvp_required
      AND l.is_active
      AND NOT EXISTS (
        SELECT 1
        FROM interaction_rule_copy irc
        JOIN risk_levels rl ON rl.id = ir.base_risk_level_id
        JOIN translations title ON title.text_id = ir.title_text_id AND title.locale_id = irc.locale_id
        JOIN translations risk_label ON risk_label.text_id = rl.label_text_id AND risk_label.locale_id = irc.locale_id
        JOIN translations headline ON headline.text_id = irc.headline_text_id AND headline.locale_id = irc.locale_id
        JOIN translations explanation ON explanation.text_id = irc.one_sentence_explanation_text_id AND explanation.locale_id = irc.locale_id
        JOIN translations prompt ON prompt.text_id = irc.conversation_prompt_text_id AND prompt.locale_id = irc.locale_id
        WHERE irc.interaction_rule_id = ir.id
          AND irc.locale_id = l.id
          AND irc.review_status = 'approved'
      )
  )
  AND EXISTS (
    SELECT 1
    FROM interaction_rule_sources irs
    JOIN evidence_sources es ON es.id = irs.evidence_source_id
    WHERE irs.interaction_rule_id = ir.id
      AND es.verification_status = 'approved'
  )
  AND NOT EXISTS (
    SELECT 1
    FROM evidence_findings ef
    WHERE ef.interaction_rule_id = ir.id
      AND ef.status NOT IN ('approved', 'retired')
  )
  AND NOT EXISTS (
    SELECT 1
    FROM rule_condition_groups rcg
    WHERE rcg.interaction_rule_id = ir.id
      AND rcg.status <> 'approved'
  )
  AND NOT EXISTS (
    SELECT 1
    FROM rule_condition_groups rcg
    JOIN rule_conditions rc ON rc.condition_group_id = rcg.id
    WHERE rcg.interaction_rule_id = ir.id
      AND rc.status <> 'approved'
  )
  AND NOT EXISTS (
    SELECT 1
    FROM rule_condition_groups rcg
    JOIN rule_conditions rc ON rc.condition_group_id = rcg.id
    WHERE rcg.interaction_rule_id = ir.id
      AND rc.condition_kind IN ('item_dose', 'measurement_value')
      AND NOT EXISTS (
        SELECT 1
        FROM rule_condition_sources rcs
        JOIN evidence_sources es ON es.id = rcs.evidence_source_id
        WHERE rcs.rule_condition_id = rc.id
          AND es.verification_status = 'approved'
      )
  )
  AND NOT EXISTS (
    SELECT 1
    FROM timing_recommendations tr
    WHERE tr.interaction_rule_id = ir.id
      AND tr.status <> 'approved'
  )
  AND NOT EXISTS (
    SELECT 1
    FROM rule_risk_modifiers rrm
    WHERE rrm.interaction_rule_id = ir.id
      AND rrm.status <> 'retired'
      AND (
        rrm.status <> 'approved'
        OR NOT EXISTS (
          SELECT 1
          FROM rule_risk_modifier_sources rrms
          JOIN evidence_sources es ON es.id = rrms.evidence_source_id
          WHERE rrms.rule_risk_modifier_id = rrm.id
            AND es.verification_status = 'approved'
        )
        OR EXISTS (
          SELECT 1
          FROM rule_condition_groups rcg
          LEFT JOIN rule_conditions rc ON rc.condition_group_id = rcg.id
          WHERE rcg.rule_risk_modifier_id = rrm.id
            AND (rcg.status <> 'approved' OR rc.status <> 'approved')
        )
      )
  );

-- A rule matches when every required slot has at least one of its concepts
-- among the user's current profile items. A slot is one participant, or all
-- participants sharing an alternative_group.
CREATE OR REPLACE FUNCTION rule_required_slots_met(p_rule_id bigint, p_user_id bigint)
RETURNS boolean
LANGUAGE sql
STABLE
AS $$
  SELECT NOT EXISTS (
    SELECT 1
    FROM interaction_rule_participants irp
    WHERE irp.interaction_rule_id = p_rule_id
      AND irp.required_for_match = true
    GROUP BY COALESCE(irp.alternative_group::bigint, -irp.id)
    HAVING NOT bool_or(EXISTS (
      SELECT 1
      FROM user_profile_items upi
      WHERE upi.user_id = p_user_id
        AND upi.concept_id = irp.concept_id
        AND upi.is_current = true
    ))
  );
$$;

CREATE OR REPLACE VIEW user_public_rule_matches AS
SELECT
  upi.user_id,
  ir.id AS interaction_rule_id,
  ir.public_id AS rule_public_id,
  ir.title_text_id,
  title_et.text AS title_et,
  title_en.text AS title_en,
  rl.code AS base_risk_level
FROM public_interaction_rule_eligibility eligible
JOIN interaction_rules ir ON ir.id = eligible.interaction_rule_id
JOIN risk_levels rl ON rl.id = ir.base_risk_level_id
LEFT JOIN translations title_et ON title_et.text_id = ir.title_text_id
  AND title_et.locale_id = (SELECT id FROM locales WHERE code = 'et')
LEFT JOIN translations title_en ON title_en.text_id = ir.title_text_id
  AND title_en.locale_id = (SELECT id FROM locales WHERE code = 'en')
JOIN user_profile_items upi ON upi.is_current = true
GROUP BY upi.user_id, ir.id, ir.public_id, ir.title_text_id, title_et.text, title_en.text, rl.code
HAVING rule_required_slots_met(ir.id, upi.user_id);

CREATE OR REPLACE FUNCTION public_rule_matches_for_user(
  p_user_id bigint,
  p_locale_id bigint DEFAULT NULL
)
RETURNS TABLE (
  user_id bigint,
  user_uid uuid,
  interaction_rule_id bigint,
  interaction_rule_uid uuid,
  rule_public_id text,
  locale text,
  title text,
  risk_label text,
  headline text,
  one_sentence_explanation text,
  conversation_prompt text,
  emergency_note text,
  base_risk_level text
)
LANGUAGE sql
STABLE
AS $$
  WITH matching_rules AS (
    SELECT ir.id
    FROM public_interaction_rule_eligibility eligible
    JOIN interaction_rules ir ON ir.id = eligible.interaction_rule_id
    WHERE rule_required_slots_met(ir.id, p_user_id)
  )
  SELECT
    u.id AS user_id,
    u.uid AS user_uid,
    ir.id AS interaction_rule_id,
    ir.uid AS interaction_rule_uid,
    ir.public_id AS rule_public_id,
    l.code AS locale,
    title.text AS title,
    risk_label.text AS risk_label,
    headline.text AS headline,
    explanation.text AS one_sentence_explanation,
    prompt.text AS conversation_prompt,
    emergency.text AS emergency_note,
    rl.code AS base_risk_level
  FROM matching_rules mr
  JOIN users u ON u.id = p_user_id
  JOIN interaction_rules ir ON ir.id = mr.id
  JOIN interaction_rule_copy irc ON irc.interaction_rule_id = ir.id
  JOIN locales l ON l.id = irc.locale_id
  JOIN risk_levels rl ON rl.id = ir.base_risk_level_id
  JOIN translations title ON title.text_id = ir.title_text_id AND title.locale_id = irc.locale_id
  JOIN translations risk_label ON risk_label.text_id = rl.label_text_id AND risk_label.locale_id = irc.locale_id
  JOIN translations headline ON headline.text_id = irc.headline_text_id AND headline.locale_id = irc.locale_id
  JOIN translations explanation ON explanation.text_id = irc.one_sentence_explanation_text_id AND explanation.locale_id = irc.locale_id
  JOIN translations prompt ON prompt.text_id = irc.conversation_prompt_text_id AND prompt.locale_id = irc.locale_id
  LEFT JOIN translations emergency ON emergency.text_id = irc.emergency_note_text_id AND emergency.locale_id = irc.locale_id
  WHERE irc.review_status = 'approved'
    AND (p_locale_id IS NULL OR irc.locale_id = p_locale_id);
$$;

-- ---------------------------------------------------------------------------
-- Audit: new tables get the updated_at trigger (001 attached it only to the
-- tables that existed then).
-- ---------------------------------------------------------------------------
DO $$
DECLARE
  tbl text;
BEGIN
  FOR tbl IN
    SELECT c.table_name
    FROM information_schema.columns c
    JOIN information_schema.tables t
      ON t.table_schema = c.table_schema AND t.table_name = c.table_name
    WHERE c.table_schema = current_schema()
      AND c.column_name = 'updated_at'
      AND t.table_type = 'BASE TABLE'
      AND NOT EXISTS (
        SELECT 1 FROM pg_trigger
        WHERE tgrelid = format('%I.%I', c.table_schema, c.table_name)::regclass
          AND tgname = 'set_' || c.table_name || '_updated_at'
      )
    ORDER BY c.table_name
  LOOP
    EXECUTE format(
      'CREATE TRIGGER %I BEFORE UPDATE ON %I FOR EACH ROW EXECUTE FUNCTION set_updated_at()',
      'set_' || tbl || '_updated_at',
      tbl
    );
  END LOOP;
END;
$$;

COMMIT;
