CREATE OR REPLACE FUNCTION public_rule_matches_for_user(
  p_user_id bigint,
  p_locale_id bigint DEFAULT NULL
)
RETURNS TABLE (
  user_id bigint,
  user_uid uuid,
  interaction_rule_id bigint,
  interaction_rule_uid uuid,
  rule_public_id text,
  locale text,
  title text,
  risk_label text,
  headline text,
  one_sentence_explanation text,
  conversation_prompt text,
  emergency_note text,
  base_risk_level text
)
LANGUAGE sql
STABLE
AS $$
  WITH matching_rules AS (
    SELECT ir.id
    FROM public_interaction_rule_eligibility eligible
    JOIN interaction_rules ir ON ir.id = eligible.interaction_rule_id
    WHERE NOT EXISTS (
      SELECT 1
      FROM interaction_rule_participants irp
      WHERE irp.interaction_rule_id = ir.id
        AND irp.required_for_match = true
        AND NOT EXISTS (
          SELECT 1
          FROM user_profile_items upi
          WHERE upi.user_id = p_user_id
            AND upi.concept_id = irp.concept_id
            AND upi.is_current = true
        )
    )
  )
  SELECT
    u.id AS user_id,
    u.uid AS user_uid,
    ir.id AS interaction_rule_id,
    ir.uid AS interaction_rule_uid,
    ir.public_id AS rule_public_id,
    l.code AS locale,
    title.text AS title,
    risk_label.text AS risk_label,
    headline.text AS headline,
    explanation.text AS one_sentence_explanation,
    prompt.text AS conversation_prompt,
    emergency.text AS emergency_note,
    rl.code AS base_risk_level
  FROM matching_rules mr
  JOIN users u ON u.id = p_user_id
  JOIN interaction_rules ir ON ir.id = mr.id
  JOIN interaction_rule_copy irc ON irc.interaction_rule_id = ir.id
  JOIN locales l ON l.id = irc.locale_id
  JOIN risk_levels rl ON rl.id = ir.base_risk_level_id
  JOIN translations title ON title.text_id = ir.title_text_id AND title.locale_id = irc.locale_id
  JOIN translations risk_label ON risk_label.text_id = rl.label_text_id AND risk_label.locale_id = irc.locale_id
  JOIN translations headline ON headline.text_id = irc.headline_text_id AND headline.locale_id = irc.locale_id
  JOIN translations explanation ON explanation.text_id = irc.one_sentence_explanation_text_id AND explanation.locale_id = irc.locale_id
  JOIN translations prompt ON prompt.text_id = irc.conversation_prompt_text_id AND prompt.locale_id = irc.locale_id
  LEFT JOIN translations emergency ON emergency.text_id = irc.emergency_note_text_id AND emergency.locale_id = irc.locale_id
  WHERE irc.review_status = 'approved'
    AND (p_locale_id IS NULL OR irc.locale_id = p_locale_id);
$$;

