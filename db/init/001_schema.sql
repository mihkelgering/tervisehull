CREATE TABLE rule_conditions (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  uid uuid NOT NULL DEFAULT gen_random_uuid() UNIQUE,
  condition_group_id bigint NOT NULL REFERENCES rule_condition_groups(id) ON DELETE CASCADE,
  condition_kind text NOT NULL CHECK (
    condition_kind IN ('has_concept', 'item_dose', 'item_frequency', 'measurement_value', 'condition_status', 'observation_value', 'demographic_value', 'profile_flag')
  ),
  concept_id bigint REFERENCES health_concepts(id) ON DELETE RESTRICT,
  measurement_type_id bigint,
  profile_risk_factor_id bigint,
  field_name text,
  operator text NOT NULL CHECK (
    operator IN ('exists', 'not_exists', 'equals', 'not_equals', 'greater_than', 'greater_than_or_equal', 'less_than', 'less_than_or_equal', 'between', 'in', 'contains')
  ),
  numeric_value numeric,
  numeric_min numeric,
  numeric_max numeric,
  unit_id bigint REFERENCES units(id) ON DELETE RESTRICT,
  text_value text,
  boolean_value boolean,
  quantity_basis text CHECK (
    quantity_basis IS NULL OR quantity_basis IN ('per_dose', 'daily_total', 'weekly_total', 'current_value', 'latest_value', 'average_recent', 'any_recorded')
  ),
  lookback_days int,
  missing_data_behavior text NOT NULL DEFAULT 'condition_not_met' CHECK (
    missing_data_behavior IN ('condition_not_met', 'flag_missing_context', 'condition_met')
  ),
  status text NOT NULL CHECK (status IN ('draft', 'approved', 'retired')),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT numeric_conditions_need_unit CHECK (
    condition_kind NOT IN ('item_dose', 'measurement_value') OR unit_id IS NOT NULL
  )
