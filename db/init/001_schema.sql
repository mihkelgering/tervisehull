CREATE TABLE interaction_rules (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  uid uuid NOT NULL DEFAULT gen_random_uuid() UNIQUE,
  public_id text NOT NULL UNIQUE,
  title_text_id bigint NOT NULL REFERENCES translation_keys(id) ON DELETE RESTRICT,
  interaction_type text NOT NULL CHECK (
    interaction_type IN ('drug_food', 'drug_supplement', 'drug_drug', 'drug_condition', 'drug_measurement', 'supplement_condition', 'supplement_measurement', 'general_factor')
  ),
  rule_scope text NOT NULL DEFAULT 'general_interaction' CHECK (
    rule_scope IN ('general_interaction', 'personal_risk_flag', 'timing_context', 'evidence_note')
  ),
  base_risk_level_id bigint NOT NULL REFERENCES risk_levels(id) ON DELETE RESTRICT,
