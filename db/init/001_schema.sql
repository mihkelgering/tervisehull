CREATE EXTENSION IF NOT EXISTS pgcrypto;
CREATE EXTENSION IF NOT EXISTS citext;

CREATE TABLE user_roles (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  uid uuid NOT NULL DEFAULT gen_random_uuid() UNIQUE,
  code text NOT NULL UNIQUE,
  display_name text NOT NULL,
  can_publish_directly boolean NOT NULL DEFAULT false,
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT user_roles_code_not_empty CHECK (length(trim(code)) > 0)
);

CREATE TABLE units (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  uid uuid NOT NULL DEFAULT gen_random_uuid() UNIQUE,
  code text NOT NULL UNIQUE,
  display_name text NOT NULL,
  ucum_code text,
  unit_family text NOT NULL CHECK (unit_family IN ('mass', 'pressure', 'time', 'count', 'volume', 'other')),
  is_active boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT units_code_not_empty CHECK (length(trim(code)) > 0)
);

CREATE TABLE data_sources (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  uid uuid NOT NULL DEFAULT gen_random_uuid() UNIQUE,
  code text NOT NULL UNIQUE,
  display_name text NOT NULL,
  is_user_entered boolean NOT NULL DEFAULT false,
  is_clinician_entered boolean NOT NULL DEFAULT false,
  is_device_generated boolean NOT NULL DEFAULT false,
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT data_sources_code_not_empty CHECK (length(trim(code)) > 0)
);

CREATE TABLE users (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  uid uuid NOT NULL DEFAULT gen_random_uuid() UNIQUE,
  email citext NOT NULL UNIQUE,
  password_hash text,
  role_id bigint NOT NULL REFERENCES user_roles(id) ON DELETE RESTRICT,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  deleted_at timestamptz
);

CREATE INDEX idx_users_role ON users(role_id);

CREATE TABLE user_sessions (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  uid uuid NOT NULL DEFAULT gen_random_uuid() UNIQUE,
  user_id bigint NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  expires_at timestamptz NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX idx_user_sessions_user_expires ON user_sessions(user_id, expires_at);

CREATE TABLE locales (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  uid uuid NOT NULL DEFAULT gen_random_uuid() UNIQUE,
  code char(2) NOT NULL UNIQUE,
  display_name text NOT NULL,
  is_mvp_required boolean NOT NULL DEFAULT false,
  is_active boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT locales_code_format CHECK (code ~ '^[a-z]{2}$')
);

CREATE TABLE countries (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  uid uuid NOT NULL DEFAULT gen_random_uuid() UNIQUE,
  code char(2) NOT NULL UNIQUE,
  display_name text NOT NULL,
  is_active boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT countries_code_format CHECK (code ~ '^[A-Z]{2}$')
);

CREATE TABLE translation_keys (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  uid uuid NOT NULL DEFAULT gen_random_uuid() UNIQUE,
  key text NOT NULL UNIQUE,
  description text,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT translation_keys_key_not_empty CHECK (length(trim(key)) > 0)
);

CREATE TABLE translations (
  text_id bigint NOT NULL REFERENCES translation_keys(id) ON DELETE CASCADE,
  locale_id bigint NOT NULL REFERENCES locales(id) ON DELETE RESTRICT,
  text text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (text_id, locale_id),
  CONSTRAINT translations_text_not_empty CHECK (length(trim(text)) > 0)
);

CREATE INDEX idx_translations_locale_text_id ON translations(locale_id, text_id);

CREATE OR REPLACE FUNCTION set_updated_at()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
  NEW.updated_at = now();
  RETURN NEW;
END;
$$;

CREATE TABLE health_concepts (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  uid uuid NOT NULL DEFAULT gen_random_uuid() UNIQUE,
  public_id text NOT NULL UNIQUE,
  display_name_text_id bigint NOT NULL REFERENCES translation_keys(id) ON DELETE RESTRICT,
  concept_type text NOT NULL CHECK (
    concept_type IN (
      'active_substance', 'drug_group', 'drug_product_family',
      'supplement', 'supplement_group', 'nutrient',
      'food', 'food_group', 'drink', 'lifestyle_factor',
      'condition', 'diagnosis', 'observation', 'measurement_type', 'lab_marker'
    )
  ),
  concept_category text CHECK (
    concept_category IS NULL OR concept_category IN (
      'drug', 'supplement', 'food_drink', 'condition',
      'observation', 'measurement', 'lifestyle', 'population', 'other'
    )
  ),
  description_text_id bigint REFERENCES translation_keys(id) ON DELETE RESTRICT,
  external_code_system text,
  external_code text,
  status text NOT NULL CHECK (status IN ('draft', 'needs_review', 'approved', 'published', 'retired')),
  review_status text NOT NULL DEFAULT 'not_started' CHECK (
    review_status IN ('not_started', 'in_review', 'changes_requested', 'approved', 'rejected')
  ),
  can_trigger_matching boolean NOT NULL DEFAULT true,
  created_by_user_id bigint REFERENCES users(id) ON DELETE SET NULL,
  approved_by_user_id bigint REFERENCES users(id) ON DELETE SET NULL,
  approved_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX idx_health_concepts_type_status ON health_concepts(concept_type, status);
CREATE INDEX idx_health_concepts_category_status ON health_concepts(concept_category, status);

CREATE TABLE concept_aliases (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  uid uuid NOT NULL DEFAULT gen_random_uuid() UNIQUE,
  concept_id bigint NOT NULL REFERENCES health_concepts(id) ON DELETE CASCADE,
