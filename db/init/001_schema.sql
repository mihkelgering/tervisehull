CREATE INDEX idx_concept_alias_lookup ON concept_aliases(lower(alias), locale_id, status);
CREATE INDEX idx_concept_aliases_concept ON concept_aliases(concept_id);
CREATE INDEX idx_concept_aliases_verification_source ON concept_aliases(verification_source_id);
CREATE INDEX idx_concept_aliases_country ON concept_aliases(country_id);

CREATE TABLE concept_relationships (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
